#!/usr/bin/env python3
"""Install a private shared copy of trusted preview code and optionally render systemd units."""
import argparse
import grp
import hashlib
import ipaddress
import json
import os
from pathlib import Path
import pwd
import shutil
import subprocess
import sys

import config
from preview import lock, write

HERE = Path(__file__).resolve().parent
SOURCES = ("preview.py", "config.py", "lan.py", "service_router.py", "install_network.py", "cleanup.py", "tracker_update.py")
MARKER = "# Generated by Genie preview tools.\n"


def atomic_text(path, text, mode=0o600):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text)
    temporary.chmod(mode)
    temporary.replace(path)


def deploy(home):
    """Versioned code keeps running workers on one coherent set of modules."""
    home.mkdir(parents=True, exist_ok=True, mode=0o700)
    home.chmod(0o700)
    key = hashlib.sha256(b"".join(name.encode() + (HERE / name).read_bytes() for name in SOURCES)).hexdigest()[:20]
    release = home / "releases" / key
    release.mkdir(parents=True, exist_ok=True)
    for name in SOURCES:
        destination = release / name
        content = (HERE / name).read_text()
        if destination.exists() and destination.read_text() != content:
            raise RuntimeError("Preserving modified installed code: " + str(destination))
        if not destination.exists():
            atomic_text(destination, content)
    with lock(home / "install.lock"):
        current = home / "code-current"
        temporary = home / "code-next"
        temporary.unlink(missing_ok=True)
        temporary.symlink_to(Path("releases") / key, target_is_directory=True)
        temporary.replace(current)
        for name in ("preview.py", "lan.py", "service_router.py", "tracker_update.py"):
            # Installed entry points derive their private home from their own location.
            wrapper = ('#!/usr/bin/env python3\n"""Installed Genie preview entry point."""\n'
                       'from pathlib import Path\nimport runpy\nimport sys\n'
                       'home = Path(__file__).resolve().parent\n'
                       'code = (home / "code-current").resolve()\n'
                       'sys.path.insert(0, str(code))\n'
                       'sys.argv[1:1] = ["--home", str(home)]\n'
                       f'runpy.run_path(str(code / {name!r}), run_name="__main__")\n')
            atomic_text(home / name, wrapper)
        local = home / "local.json"
        if not local.exists():
            atomic_text(local, (HERE / "config.example.json").read_text())
        # Keep legacy fields for older running gateways; load() takes settings only from local.json.
        network = home / "config.json"
        if network.exists():
            before = config.read_json(network, {})
            legacy = {k: v for k, v in before.items() if k in config.DEFAULTS and v != config.DEFAULTS[k]}
            if legacy:
                settings = config.read_json(local, {})
                write(local, dict(legacy, **settings))
    return release


def quoted(value, executable=False):
    text = str(value)
    if any(char in text for char in ("\n", "\r", "\0")):
        raise ValueError("A systemd value contains a line break or NUL")
    text = text.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    if executable:
        text = text.replace("$", "$$")
    return '"' + text + '"'


def command(*args):
    return " ".join(quoted(arg, executable=True) for arg in args)


def scalar(value):
    # User/Group/WorkingDirectory do not use ExecStart's argument quoting.
    text = str(value)
    if any(char in text for char in ("\n", "\r", "\0")):
        raise ValueError("A systemd value contains a line break or NUL")
    return text.replace("%", "%%")


def user_units(home, services=False, lan=False, tracker=False, root=None):
    units = {}
    python = sys.executable
    if lan:
        units["genie-mdns.service"] = (
            "[Unit]\nDescription=Genie environment names over mDNS\nAfter=network-online.target\n\n"
            "[Service]\nExecStart=" + command(python, home / "lan.py", "mdns") +
            "\nRestart=on-failure\nRestartSec=5\n\n[Install]\nWantedBy=default.target\n")
    if services:
        tailscaled = shutil.which("tailscaled")
        if not tailscaled:
            raise RuntimeError("tailscaled is required for --services")
        units["genie-tailscale-services.service"] = (
            "[Unit]\nDescription=Isolated Tailscale identity for Genie Services\nAfter=network-online.target\n\n"
            "[Service]\nType=simple\nUMask=0077\nRuntimeDirectory=genie-services\nRuntimeDirectoryMode=0700\n"
            "ExecStart=" + command(tailscaled, "--tun=userspace-networking", "--port=0",
                                   "--socket=" + config.runtime_socket(), "--statedir=" + str(home / "services/state")) +
            "\nRestart=on-failure\nRestartSec=5\n\n[Install]\nWantedBy=default.target\n")
        units["genie-service-router.service"] = (
            "[Unit]\nDescription=Channel routing for named Genie Tailscale Services\nAfter=network-online.target\n\n"
            "[Service]\nType=simple\nExecStart=" + command(python, home / "service_router.py") +
            "\nRestart=on-failure\nRestartSec=5\n\n[Install]\nWantedBy=default.target\n")
    if tracker:
        units["genie-tracker-update.service"] = (
            "[Unit]\nDescription=Update the local Genie tracker from verified dev\nAfter=network-online.target docker.service\n\n"
            "[Service]\nType=oneshot\nUMask=0077\nNice=10\nCPUWeight=25\nTimeoutStartSec=30min\n"
            "ExecStart=" + command(python, home / "tracker_update.py", "--root", root) + "\n")
        units["genie-tracker-update.timer"] = (
            "[Unit]\nDescription=Check dev for local Genie tracker updates\n\n"
            "[Timer]\nOnBootSec=30s\nOnUnitInactiveSec=2min\nRandomizedDelaySec=10s\n\n"
            "[Install]\nWantedBy=timers.target\n")
    return units


def system_units(home, settings):
    interface = config.lan_interface(settings)
    addresses = {"127.0.0.1", config.lan_address(interface)}
    if shutil.which("tailscale"):
        status = config.json_command(["tailscale", "status", "--json"])
        if status.get("BackendState") == "Running":
            addresses.update(address for address in status.get("Self", {}).get("TailscaleIPs", [])
                             if ipaddress.ip_address(address).version == 4)
    user = pwd.getpwuid(os.getuid())
    group = grp.getgrgid(user.pw_gid).gr_name
    socket = ("[Unit]\nDescription=Genie local and tailnet HTTP names\nAfter=network-online.target tailscaled.service\n\n"
              "[Socket]\n" + "".join(f"ListenStream={address}:80\n" for address in sorted(addresses)) +
              "FreeBind=true\nNoDelay=true\n\n[Install]\nWantedBy=sockets.target\n")
    service = ("[Unit]\nDescription=Genie host routing for isolated preview environments\n"
               "Requires=genie-local-proxy.socket\nAfter=genie-local-proxy.socket\n\n"
               "[Service]\nType=simple\nUser=" + scalar(user.pw_name) + "\nGroup=" + scalar(group) +
               "\nWorkingDirectory=" + scalar(home) + "\nExecStart=" + command(sys.executable, home / "lan.py", "serve") +
               "\nNoNewPrivileges=true\nPrivateTmp=true\nProtectSystem=strict\nProtectHome=read-only\n"
               "RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX\nRestart=on-failure\n")
    return {"genie-local-proxy.socket": socket, "genie-local-proxy.service": service}


def install_user_units(home, units):
    destination = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "systemd/user"
    # Preflight every file before changing any. Recognize this installation's legacy units.
    for name in units:
        path = destination / name
        if path.exists() and not path.read_text().startswith(MARKER) and str(home) not in path.read_text():
            raise RuntimeError("Preserving unrelated user unit: " + str(path))
    for name, body in units.items():
        path = destination / name
        if path.exists() and path.read_text() != MARKER + body:
            backup = path.with_name(name + ".before-genie-preview")
            if not backup.exists():
                shutil.copy2(path, backup)
        atomic_text(path, MARKER + body)


def main():
    os.umask(0o077)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--lan", action="store_true", help="Discover LAN interface/addresses and render mDNS and HTTP units")
    parser.add_argument("--services", action="store_true", help="Render separate Tailscale daemon and channel router units")
    parser.add_argument("--tracker-updater", action="store_true", help="Render a host-side verified-dev tracker updater timer")
    parser.add_argument("--install-user-units", action="store_true", help="Install rendered user units; does not start/restart services")
    args = parser.parse_args()
    if os.getuid() == 0:
        raise RuntimeError("Run this installer as the preview owner, not root")
    home = config.home_for_repo(args.root)
    release = deploy(home)
    settings = config.load(home)
    from preview import git
    primary = Path(git(args.root, "worktree", "list", "--porcelain").splitlines()[0].removeprefix("worktree "))
    units = user_units(home, args.services, args.lan, args.tracker_updater, primary)
    system = system_units(home, settings) if args.lan else {}
    for kind, group in (("user", units), ("system", system)):
        for name, body in group.items():
            atomic_text(home / "units" / kind / name, MARKER + body)
    if units:
        subprocess.run(["systemd-analyze", "--user", "verify",
                        *(str(home / "units/user" / name) for name in units)], check=True)
    if system:
        subprocess.run(["systemd-analyze", "verify",
                        *(str(home / "units/system" / name) for name in system)], check=True)
    if args.install_user_units:
        install_user_units(home, units)
        subprocess.run(["systemctl", "--user", "daemon-reload"], check=True)
    print(json.dumps({"home": str(home), "code": str(release), "config": str(home / "local.json"),
                      "units": str(home / "units"), "userUnits": list(units), "systemUnits": list(system)}, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, ValueError, OSError, subprocess.CalledProcessError) as exc:
        sys.exit("genie-preview install: " + str(exc))
