#!/usr/bin/env python3
"""Install reviewed system units and optionally enable multi-label mDNS resolution."""
import argparse
import os
from pathlib import Path
import shutil
import subprocess

MARKER = "# Generated by Genie preview tools.\n"
NAMES = ("genie-local-proxy.socket", "genie-local-proxy.service")


def resolver_text(before):
    lines = before.splitlines(keepends=True)
    for index, line in enumerate(lines):
        if not line.startswith("hosts:"):
            continue
        # Preserve comments and module-specific actions; move files only when it has no action.
        text, separator, comment = line.partition("#")
        words = text.split()
        if "files" not in words or (words.index("files") + 1 < len(words) and words[words.index("files") + 1].startswith("[")):
            raise RuntimeError("Unrecognized files resolver; configure nss-mdns manually")
        words.remove("files")
        words.insert(1, "files")
        if "mdns4" not in words:
            minimal = next((i for i, word in enumerate(words) if word in {"mdns_minimal", "mdns4_minimal"}), None)
            if minimal is None:
                raise RuntimeError("No existing nss-mdns resolver; install/configure it before using --mdns")
            words.insert(minimal, "mdns4")
        lines[index] = " ".join(words) + (" #" + comment.rstrip("\n") if separator else "") + "\n"
        return "".join(lines)
    raise RuntimeError("No hosts resolver line found; preserving nsswitch.conf")


def backup(path):
    saved = path.with_name(path.name + ".genie-preview.bak")
    if path.exists() and not saved.exists():
        shutil.copy2(path, saved)


def install(units, etc=Path("/etc"), mdns=False):
    bodies = {name: (units / name).read_text() for name in NAMES}
    if not all(body.startswith(MARKER) for body in bodies.values()):
        raise RuntimeError("Expected generated, reviewed Genie units")
    system = etc / "systemd/system"
    for name, body in bodies.items():
        destination = system / name
        if destination.exists() and destination.read_text() != body:
            existing = destination.read_text()
            # Permit only marked units or this helper's legacy service/socket pair.
            legacy = "Description=Genie " in existing and (
                "genie-preview/lan.py serve" in existing if name.endswith(".service") else
                "Description=Genie local and tailnet HTTP names" in existing)
            if not existing.startswith(MARKER) and not legacy:
                raise RuntimeError("Preserving unrelated system unit: " + str(destination))
    resolver = etc / "nsswitch.conf"
    after = resolver_text(resolver.read_text()) if mdns else None
    # Finish preflight before modifying any system files.
    if mdns:
        if after != resolver.read_text():
            backup(resolver)
            resolver.write_text(after)
        allow = etc / "mdns.allow"
        existing = allow.read_text() if allow.exists() else ""
        suffixes = ("genie.local", ".genie.local", "genie.local.", ".genie.local.")
        missing = [suffix for suffix in suffixes if suffix not in existing.splitlines()]
        if missing:
            backup(allow)
            allow.write_text(existing + "\n# Genie multi-label mDNS names\n" + "\n".join(missing) + "\n")
            allow.chmod(0o644)
    for name, body in bodies.items():
        destination = system / name
        backup(destination)
        destination.write_text(body)
        destination.chmod(0o644)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--units", type=Path, required=True, help="Reviewed units/system directory")
    parser.add_argument("--mdns", action="store_true", help="Enable full nss-mdns for Genie suffixes, preserving backups")
    args = parser.parse_args()
    if os.getuid() != 0:
        parser.error("Run this system-only step through sudo or pkexec")
    subprocess.run(["systemd-analyze", "verify", *(str(args.units / name) for name in NAMES)], check=True)
    install(args.units, mdns=args.mdns)
    subprocess.run(["systemctl", "daemon-reload"], check=True)
    print("Installed units. Start/restart genie-local-proxy.socket and genie-local-proxy.service after review.")
