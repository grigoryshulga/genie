import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const pluginOutput = new URL("../../design-system/figma/code.js", import.meta.url);
export function buildPlugin() {
  const sources = ["task-screen.js", "library.js", "screen.js", "importer.js"];
  return "/* Generated by node scripts/design-system/build-plugin.mjs; edit figma/src instead. */\n"
    + sources.map((name) => readFileSync(new URL(`../../design-system/figma/src/${name}`, import.meta.url), "utf8").trimEnd()).join("\n\n") + "\n";
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = buildPlugin();
  if (process.argv.includes("--check")) {
    if (readFileSync(pluginOutput, "utf8") !== output) throw new Error("Figma plugin bundle is stale; run node scripts/design-system/build-plugin.mjs");
  } else writeFileSync(pluginOutput, output);
}
