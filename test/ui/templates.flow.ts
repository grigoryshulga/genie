import { readFile } from "node:fs/promises";
import { expect, test } from "@playwright/test";
import { TEMPLATE_FILE } from "./template-data.ts";
import { parseTemplateTransfer } from "../../web/src/entities/agent-config/template-transfer.ts";
const id = "template-workspace-test", importedId = "template-workspace-import";
const headers = { "x-genie": "1" };

test("template workspace persists composition, portable files, conflict protection and JSON audit pages", async ({ page, request }) => {
  const created = await request.put(`/api/templates/${id}`, { headers, data: { template: TEMPLATE_FILE, baseHash: "" } });
  expect(created.ok(), await created.text()).toBe(true);
  try {
    await page.goto(`/agents?tab=templates&id=${id}`);
    await expect(page.getByRole("heading", { name: TEMPLATE_FILE.title, exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Редактировать шаблон", exact: true }).click();
    const member = page.locator(".template-member").first();
    await member.getByLabel("Ключ", { exact: true }).fill("builder");
    await member.getByLabel("Имя", { exact: true }).fill("robot");
    await member.getByLabel("Размышление", { exact: true }).selectOption("max");
    await member.getByLabel("Инструкции участнику", { exact: true }).fill("Keep the API compatible");
    const relationCount = await page.locator(".template-relation-editor").count();
    await page.locator(".split-main").evaluate((el) => el.scrollTo(0, 0));
    await page.locator("svg.connectable .node:not(.orch)").first().dragTo(page.locator("svg.connectable .node.orch"));
    await expect(page.locator(".template-relation-editor")).toHaveCount(relationCount + 1);
    await page.getByRole("tab", { name: "Настройки", exact: true }).click();
    await page.getByLabel("Описание", { exact: true }).fill("Saved across both tabs");
    await page.getByRole("button", { name: "Сохранить", exact: true }).click();
    await expect(page.locator(".template-editor")).toHaveCount(0);
    const stored = await (await request.get(`/api/templates/${id}`)).json();
    expect(stored.template.members[0]).toMatchObject({ key: "builder", name: "robot", thinking: "max", instructions: "Keep the API compatible", model: "anthropic/claude-sonnet-4-6" });
    expect(stored.template.relations.some((r: { from: string; to: string[]; type: string }) => r.from === "builder" && r.to.includes("orchestrator") && r.type === "reports")).toBe(true);
    expect(stored.template.relations.some((r: { from: string }) => r.from === "builder")).toBe(true);
    expect(stored.template.relations.every((r: { from: string; to: string[] }) => r.from !== "executor" && !r.to.includes("executor"))).toBe(true);
    await page.reload();
    await expect(page.locator(".config-header")).toContainText("Saved across both tabs");
    const downloading = page.waitForEvent("download");
    await page.getByRole("button", { name: "Экспорт шаблона", exact: true }).click();
    const download = await downloading;
    const portable = parseTemplateTransfer(await readFile((await download.path())!, "utf8"));
    expect(portable.members[0].thinking).toBe("max");
    await page.getByRole("button", { name: "Открыть поиск", exact: true }).click();
    const search = page.getByRole("searchbox", { name: "Поиск агентов и инструментов", exact: true }).filter({ visible: true });
    await search.fill("ABAP");
    await page.getByRole("button", { name: "Импорт шаблона", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Импорт шаблона", exact: true });
    const schemaDownload = page.waitForEvent("download");
    await dialog.getByRole("button", { name: "Скачать JSON Schema шаблона", exact: true }).click();
    expect(JSON.parse(await readFile((await (await schemaDownload).path())!, "utf8")).properties.members.items.properties.thinking).toBeDefined();
    await dialog.getByLabel("Файл шаблона (.json)").setInputFiles({ name: "team.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(portable)) });
    await expect(dialog.getByRole("checkbox", { name: /Заменить существующий шаблон/ })).not.toBeChecked();
    await expect(dialog.getByRole("button", { name: "Импортировать", exact: true })).toBeDisabled();
    await dialog.getByRole("checkbox", { name: /Заменить существующий шаблон/ }).check();
    await expect(dialog.getByRole("button", { name: "Импортировать", exact: true })).toBeEnabled();
    expect((await request.put(`/api/templates/${id}`, { headers, data: { content: stored.file.content.replace("Saved across both tabs", "Concurrent import update") } })).ok()).toBe(true);
    await dialog.getByRole("button", { name: "Импортировать", exact: true }).click();
    await expect(dialog.getByRole("alert")).toBeVisible();
    await dialog.getByLabel("Идентификатор шаблона").fill(importedId);
    await dialog.getByRole("button", { name: "Импортировать", exact: true }).click();
    await expect(dialog).toBeHidden();
    expect((await (await request.get(`/api/templates/${importedId}`)).json()).template.members).toEqual(stored.template.members);
    await page.goto(`/agents?tab=templates&id=${id}&view=settings`);
    await page.getByRole("button", { name: "Редактировать шаблон", exact: true }).click();
    await page.getByLabel("Описание", { exact: true }).fill("Conflicting draft");
    const current = await (await request.get(`/api/templates/${id}`)).json();
    expect((await request.put(`/api/templates/${id}`, { headers, data: { content: current.file.content.replace("Concurrent import update", "Concurrent editor update") } })).ok()).toBe(true);
    await page.getByRole("button", { name: "Сохранить", exact: true }).click();
    await expect(page.getByRole("alert")).toBeVisible();
    expect((await (await request.get(`/api/templates/${id}`)).json()).template.description).toBe("Concurrent editor update");
    await page.getByRole("button", { name: "Отмена", exact: true }).click();
    for (let i = 0; i < 23; i++) expect((await request.put(`/api/templates/${id}`, { headers, data: { content: stored.file.content.replace("Saved across both tabs", `Audit ${i}`) } })).ok()).toBe(true);
    await page.goto(`/agents?tab=templates&id=${id}&view=history`);
    await expect(page.locator(".config-history-table > tbody > tr")).toHaveCount(20);
    await page.locator(".config-history-table > tbody > tr").first().getByRole("button", { name: /Сравнить/ }).click();
    await expect(page.locator(".config-history-diff")).toContainText("description");
    await page.getByRole("button", { name: "Восстановить до этой правки", exact: true }).click();
    await page.getByRole("dialog").getByRole("button", { name: "Восстановить", exact: true }).click();
    await expect.poll(async () => (await (await request.get(`/api/templates/${id}`)).json()).template.description).toBe("Audit 21");
    await page.getByRole("button", { name: "Старее", exact: true }).click();
    await expect(page.locator(".config-history-pagination")).toContainText("Страница 2");
    await expect(page.getByRole("button", { name: "Старее", exact: true })).toBeDisabled();
    await page.getByRole("tab", { name: "Промпты", exact: true }).click();
    await expect(page.locator(".template-kickoff")).toHaveCount(2);
    await page.getByLabel("Задача", { exact: true }).fill("DM-2");
    await page.getByRole("button", { name: "Показать", exact: true }).click();
    await page.locator(".template-kickoff > summary").first().click();
    await expect(page.locator(".template-kickoff pre").first()).toContainText("DM-2");
    const automatic = JSON.parse(stored.file.content);
    delete automatic.relations;
    expect((await request.put(`/api/templates/${id}`, { headers, data: { template: automatic } })).ok()).toBe(true);
    await page.goto(`/agents?tab=templates&id=${id}`);
    await page.getByRole("button", { name: "Редактировать шаблон", exact: true }).click();
    await expect(page.getByLabel("Режим связей", { exact: true })).toHaveValue("auto");
    await page.locator(".template-member").first().getByLabel("Ключ", { exact: true }).fill("auto-builder");
    await page.getByRole("button", { name: "Сохранить", exact: true }).click();
    await expect(page.locator(".template-editor")).toHaveCount(0);
    const autoSaved = await (await request.get(`/api/templates/${id}`)).json();
    expect(JSON.parse(autoSaved.file.content)).not.toHaveProperty("relations");
    expect(autoSaved.template.relationsDerived).toBe(true);
    expect(autoSaved.template.relations.some((r: { from: string }) => r.from === "auto-builder")).toBe(true);
    await page.getByRole("button", { name: "Редактировать шаблон", exact: true }).click();
    await page.getByLabel("Режим связей", { exact: true }).selectOption("explicit");
    while (await page.getByRole("button", { name: "Удалить связь", exact: true }).count()) await page.getByRole("button", { name: "Удалить связь", exact: true }).first().click();
    await page.getByRole("button", { name: "Сохранить", exact: true }).click();
    await expect(page.locator(".template-editor")).toHaveCount(0);
    const empty = await (await request.get(`/api/templates/${id}`)).json();
    expect(JSON.parse(empty.file.content).relations).toEqual([]);
    expect(empty.template.relationsDerived).toBe(false);
  } finally {
    await request.delete(`/api/templates/${importedId}`, { headers });
    await request.delete(`/api/templates/${id}`, { headers });
  }
});
